SENSITIVITY_MINUTES = (5, 10, 15, 20, 30, 45, 60, 120)
DURATION_BINS = [0, 1, 10, 30, 60, 120, 300, 600, 1200, 1800, 3600, 7200, 4 * 3600, 24 * 3600, 10**9]


def _glob(table: Path) -> str:
    return sql_str(str(table / "*" / "*.parquet"))


def _fmt(v, pct: bool = False, digits: int = 1) -> str:
    if v is None:
        return ""
    if pct:
        return f"{100 * v:.{digits}f}%"
    if isinstance(v, float):
        return f"{v:,.{digits}f}"
    if isinstance(v, int):
        return f"{v:,}"
    return str(v)


def _table(headers: list[str], rows: list[list], align: str | None = None) -> str:
    align = align or "l" + "r" * (len(headers) - 1)
    sep = ["---:" if a == "r" else "---" for a in align]
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join(sep) + " |"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _month_of(day_iso: str) -> str:
    return day_iso[:7]


def write_report(paths: Paths, months: list[str] | None = None, log=print) -> Path:
    t0 = time.perf_counter()
    days = list_partitions(paths.gold_table("sessions"), "session_date")
    available = sorted({d.isoformat()[:7] for d in days})
    months = months or available
    missing = [m for m in months if m not in available]
    if missing:
        raise SystemExit(f"no gold data for {missing}; available: {available}")
    con = connect(threads=4)
    con.execute("SET memory_limit='3GB'")
    month_list = ", ".join(sql_str(m) for m in months)
    con.execute(
        f"""CREATE VIEW s AS SELECT *, strftime(session_date, '%Y-%m') AS month
            FROM read_parquet({_glob(paths.gold_table("sessions"))}, hive_partitioning=false)
            WHERE strftime(session_date, '%Y-%m') IN ({month_list})"""
    )
    con.execute(
        f"""CREATE VIEW dm AS SELECT *, strftime(session_date, '%Y-%m') AS month
            FROM read_parquet({_glob(paths.gold_table("daily_metrics"))}, hive_partitioning=false)
            WHERE strftime(session_date, '%Y-%m') IN ({month_list})"""
    )
    figs = paths.reports / "figures"
    figs.mkdir(parents=True, exist_ok=True)
    md: list[str] = [
        "# Analysis",
        "",
        "Generated by `clickstream report` from the gold tables, silver DQ reports and sessionized events. "
        f"Months: {', '.join(months)}. Session = a user's events with no gap over {config.SESSION_GAP_MINUTES} min. "
        "Sessions are assigned to the UTC date of their first event. Unless stated, figures include suspected bots.",
        "",
    ]

    # --- 1. overview ------------------------------------------------------------------------
    rows = con.execute(
        """SELECT month, sum(sessions) FILTER (population = 'all'), sum(events) FILTER (population = 'all'),
                  sum(sessions) FILTER (population = 'non_bot'), sum(revenue) FILTER (population = 'all')
           FROM dm GROUP BY 1 ORDER BY 1"""
    ).fetchall()
    users = dict(con.execute("SELECT month, count(DISTINCT user_id) FROM s GROUP BY 1").fetchall())
    md += ["## Overview", ""]
    md.append(
        _table(
            [
                "Month",
                "Events in these sessions",
                "Users",
                "Sessions starting in month",
                "Sessions, non-bot",
                "Revenue (sum of purchase prices)",
            ],
            [
                [m, _fmt(e), _fmt(users[m]), _fmt(n), _fmt(nb), _fmt(float(r), digits=0)]
                for m, n, e, nb, r in rows
            ],
        )
    )
    md.append("")

    # --- 2. data quality ----------------------------------------------------------------------
    md += _dq_section(paths, months, con)

    # --- 3. session length --------------------------------------------------------------------
    q = con.execute(
        """SELECT month, count(*), avg((n_events = 1)::INT),
             quantile_cont(duration_s, [0.25, 0.5, 0.75, 0.9, 0.99]),
             quantile_cont(duration_s, [0.25, 0.5, 0.75, 0.9, 0.99]) FILTER (n_events > 1),
             max(duration_s)
           FROM s GROUP BY 1 ORDER BY 1"""
    ).fetchall()
    md += [
        "## Session length",
        "",
        "Duration = last event time - first event time, in seconds. A single-event session has duration 0, "
        "so quantiles are given for all sessions and for sessions with 2+ events.",
        "",
    ]
    trows = []
    for m, n, single, qa, qm, mx in q:
        trows.append(
            [m, "all", _fmt(n), _fmt(single, pct=True)] + [_fmt(x, digits=0) for x in qa] + [_fmt(mx)]
        )
        trows.append([m, "2+ events", "", ""] + [_fmt(x, digits=0) for x in qm] + [""])
    md.append(
        _table(
            [
                "Month",
                "Population",
                "Sessions",
                "Single-event",
                "p25 (s)",
                "p50 (s)",
                "p75 (s)",
                "p90 (s)",
                "p99 (s)",
                "Max (s)",
            ],
            trows,
        )
    )
    md.append("")
    bin_case = " ".join(f"WHEN duration_s < {hi} THEN {k}" for k, hi in enumerate(DURATION_BINS[1:], start=1))
    bins = con.execute(f"SELECT CASE {bin_case} END AS bin, count(*) FROM s GROUP BY 1 ORDER BY 1").fetchall()
    labels = _duration_labels()
    counts = dict(bins)
    total = sum(counts.values())
    md.append(
        _table(
            ["Duration", "Sessions", "Share"],
            [
                [labels[i - 1], _fmt(counts.get(i, 0)), _fmt(counts.get(i, 0) / total, pct=True)]
                for i in range(1, len(labels) + 1)
            ],
        )
    )
    md += ["", "![Session duration distribution](figures/session_duration.png)", ""]
    _bar(
        figs / "session_duration.png",
        labels,
        [counts.get(i, 0) / total * 100 for i in range(1, len(labels) + 1)],
        "Share of sessions (%)",
        "Session duration, all months combined",
    )

    # --- 4. events per session ----------------------------------------------------------------
    buckets = [(1, 1), (2, 2), (3, 5), (6, 10), (11, 20), (21, 50), (51, 100), (101, None)]
    case = " ".join(
        f"WHEN n_events BETWEEN {lo} AND {hi} THEN {i}" if hi else f"WHEN n_events >= {lo} THEN {i}"
        for i, (lo, hi) in enumerate(buckets)
    )
    ev = dict(con.execute(f"SELECT CASE {case} END AS b, count(*) FROM s GROUP BY 1").fetchall())
    evq = con.execute(
        "SELECT quantile_cont(n_events, [0.5, 0.9, 0.99]), avg(n_events), max(n_events) FROM s"
    ).fetchone()
    blabels = [f"{lo}" if lo == hi else (f"{lo}-{hi}" if hi else f"{lo}+") for lo, hi in buckets]
    total = sum(ev.values())
    md += [
        "## Events per session",
        "",
        f"Median {_fmt(evq[0][0], digits=0)}, p90 {_fmt(evq[0][1], digits=0)}, p99 {_fmt(evq[0][2], digits=0)}, "
        f"mean {_fmt(evq[1], digits=2)}, max {_fmt(evq[2])}.",
        "",
        _table(
            ["Events", "Sessions", "Share"],
            [[b, _fmt(ev.get(i, 0)), _fmt(ev.get(i, 0) / total, pct=True)] for i, b in enumerate(blabels)],
        ),
        "",
        "![Events per session](figures/events_per_session.png)",
        "",
    ]
    _bar(
        figs / "events_per_session.png",
        blabels,
        [ev.get(i, 0) / total * 100 for i in range(len(blabels))],
        "Share of sessions (%)",
        "Events per session",
    )

    # --- 5. funnel ----------------------------------------------------------------------------
    f = con.execute(
        """SELECT month, population, sum(sessions), sum(sessions_with_view), sum(sessions_with_cart),
                  sum(sessions_with_purchase), sum(sessions_with_cart_and_purchase)
           FROM dm GROUP BY 1, 2 ORDER BY 1, 2"""
    ).fetchall()
    md += [
        "## Funnel: view -> cart -> purchase",
        "",
        "Counted as sessions that *reached* each stage, in any order. A strict view -> cart -> purchase "
        "sequence would undercount: many purchases have no cart event in the same session (last column).",
        "",
    ]
    md.append(
        _table(
            [
                "Month",
                "Population",
                "Sessions",
                "With view",
                "With cart",
                "With purchase",
                "View -> cart",
                "Cart -> purchase",
                "Session conversion",
                "Purchase sessions without a cart",
            ],
            [
                [
                    m,
                    p,
                    _fmt(n),
                    _fmt(v),
                    _fmt(c),
                    _fmt(pu),
                    _fmt(c / v, pct=True, digits=2),
                    _fmt(cp / c, pct=True, digits=2),
                    _fmt(pu / n, pct=True, digits=2),
                    _fmt((pu - cp) / pu, pct=True),
                ]
                for m, p, n, v, c, pu, cp in f
            ],
        )
    )
    md += ["", "![Funnel](figures/funnel.png)", ""]
    allrows = [r for r in f if r[1] == "all"]
    _grouped_bar(
        figs / "funnel.png",
        ["Reached cart", "Reached purchase", "Cart and purchase"],
        {m: [c / n * 100, pu / n * 100, cp / n * 100] for m, _, n, _, c, pu, cp in allrows},
        "Share of sessions (%)",
        "Sessions reaching each stage (every session has a view)",
    )

    # --- 6. conversion and duration by segment (marts) -----------------------------------------
    md += _marts_section(paths, con, months, available)

    # --- 7. vs user_session -------------------------------------------------------------------
    md += _user_session_section(paths, con, months, figs, log)

    md.append(f"_Report generated in {time.perf_counter() - t0:.0f} s._")
    out = paths.reports / "analysis.md"
    out.write_text("\n".join(md) + "\n")
    log(f"report: wrote {out}")
    return out


def _dq_section(paths: Paths, months: list[str], con) -> list[str]:
    reports = [r for r in load_reports(paths.dq, "silver") if _month_of(r["key"]) in months]
    md = ["## Data quality (silver)", ""]
    rows = []
    for m in months:
        rs = [r["metrics"] for r in reports if _month_of(r["key"]) == m]
        dup = {}
        for r in rs:
            for k, v in r["duplicates_removed_by_event_type"].items():
                dup[k] = dup.get(k, 0) + v
        quarantine = {}
        for r in rs:
            for k, v in r["quarantined_by_reason"].items():
                quarantine[k] = quarantine.get(k, 0) + v
        rows.append(
            [
                m,
                _fmt(sum(r["bronze_rows"] for r in rs)),
                _fmt(sum(r["duplicates_removed"] for r in rs)),
                ", ".join(f"{k} {v:,}" for k, v in sorted(dup.items())),
                _fmt(sum(r["purchase_duplicates_removed"] for r in rs)),
                _fmt(sum(r["purchase_duplicate_revenue_removed"] for r in rs), digits=2),
                _fmt(sum(quarantine.values()))
                + (f" ({', '.join(f'{k} {v:,}' for k, v in quarantine.items())})" if quarantine else ""),
                _fmt(sum(r["zero_price_rows"] for r in rs)),
                _fmt(sum(r["null_user_session_rows"] for r in rs)),
                _fmt(sum(r["silver_rows"] for r in rs)),
            ]
        )
    md.append(
        _table(
            [
                "Month",
                "Bronze rows",
                "Exact duplicates removed",
                "...by event type",
                "Purchase duplicates",
                "Purchase duplicate revenue removed",
                "Quarantined",
                "Zero-price rows (kept, flagged)",
                "Null user_session (kept)",
                "Silver rows",
            ],
            rows,
        )
    )
    warns = [
        (r["key"], c["name"], c["value"])
        for r in load_reports(paths.dq)
        for c in r["checks"]
        if c["severity"] == "warn" and not c["passed"] and _month_of(r["key"]) in months
    ]
    md += [
        "",
        f"Warnings across all partitions: {len(warns)}."
        + (" " + "; ".join(f"{k} {n}: {v}" for k, n, v in warns[:10]) if warns else ""),
        "",
    ]

    # bots
    flags = sql_str(str(paths.bot_flags / "*" / "*.parquet"))
    b = con.execute(
        f"""SELECT strftime(event_date, '%Y-%m') AS month, count(DISTINCT user_id), count(*), sum(events)
            FROM read_parquet({flags}, hive_partitioning=true) GROUP BY 1 ORDER BY 1"""
    ).fetchall()
    b = [r for r in b if r[0] in months]
    events = {
        m: sum(r["metrics"]["silver_rows"] for r in reports if _month_of(r["key"]) == m) for m in months
    }
    users = dict(con.execute("SELECT month, count(DISTINCT user_id) FROM s GROUP BY 1").fetchall())
    bs = dict(
        (m, (n, t))
        for m, n, t in con.execute(
            "SELECT month, count(*) FILTER (suspect_bot), count(*) FROM s GROUP BY 1"
        ).fetchall()
    )
    md += [
        "### Suspected bots",
        "",
        f"A user-day is flagged when the user has >= {config.BOT_MAX_EVENTS_PER_MINUTE} events in one calendar minute "
        f"or >= {config.BOT_MAX_EVENTS_PER_DAY} events in the UTC day (`config.py`). Flagged rows are kept; "
        "a session is `suspect_bot` if it touches a flagged user-day. Segment/conversion marts exclude them.",
        "",
        _table(
            [
                "Month",
                "Users flagged",
                "Share of users",
                "User-days flagged",
                "Events on flagged user-days",
                "Share of events",
                "Sessions flagged",
                "Share of sessions",
            ],
            [
                [
                    m,
                    _fmt(u),
                    _fmt(u / users[m], pct=True, digits=3),
                    _fmt(ud),
                    _fmt(int(e)),
                    _fmt(e / events[m], pct=True, digits=2),
                    _fmt(bs[m][0]),
                    _fmt(bs[m][0] / bs[m][1], pct=True, digits=3),
                ]
                for m, u, ud, e in b
            ],
        ),
        "",
    ]
    return md


def _marts_section(paths: Paths, con, months: list[str], available: list[str]) -> list[str]:
    marts = paths.gold_table("marts")
    md = [
        "## Conversion and session duration by segment",
        "",
        "From the gold marts (non-bot sessions"
        + ("" if months == available else f"; marts cover {', '.join(available)}")
        + "). "
        "Conversion: of sessions with any event in the segment, the share that carted / purchased in it. "
        "Duration segments use the session's *entry* event (first product seen): top-level category, brand, "
        "and price band of that product. The original 2020 take-home asked for duration by browser / OS / "
        "device; this dataset has no device fields, so these segments stand in for them.",
        "",
        "### Conversion by top-level category",
        "",
    ]
    rows = con.execute(
        f"SELECT * FROM read_parquet({sql_str(str(marts / 'conversion_by_category.parquet'))})"
    ).fetchall()
    md.append(
        _table(
            ["Category", "Sessions", "Carted", "Purchased", "Cart rate", "Purchase rate", "Revenue"],
            [
                [
                    c,
                    _fmt(n),
                    _fmt(ca),
                    _fmt(p),
                    _fmt(cr, pct=True, digits=2),
                    _fmt(pr, pct=True, digits=2),
                    _fmt(float(r), digits=0),
                ]
                for c, n, ca, p, cr, pr, r in rows
            ],
        )
    )
    md += [
        "",
        f"### Conversion by brand (top 15 by sessions, brands with >= {config.MIN_SESSIONS_PER_BRAND:,} sessions)",
        "",
    ]
    rows = con.execute(
        f"SELECT * FROM read_parquet({sql_str(str(marts / 'conversion_by_brand.parquet'))}) LIMIT 15"
    ).fetchall()
    md.append(
        _table(
            ["Brand", "Sessions", "Carted", "Purchased", "Cart rate", "Purchase rate", "Revenue"],
            [
                [
                    c,
                    _fmt(n),
                    _fmt(ca),
                    _fmt(p),
                    _fmt(cr, pct=True, digits=2),
                    _fmt(pr, pct=True, digits=2),
                    _fmt(float(r), digits=0),
                ]
                for c, n, ca, p, cr, pr, r in rows
            ],
        )
    )
    dur = sql_str(str(marts / "duration_by_segment.parquet"))
    for seg, title, extra in [
        ("category_top", "entry top-level category", ""),
        ("price_band", "entry product price band", ""),
        ("brand", "entry brand (top 15 by sessions)", " LIMIT 15"),
    ]:
        order = (
            "ORDER BY list_position(['0-10','10-50','50-100','100-250','250-500','500-1000','1000+'], segment)"
            if seg == "price_band"
            else "ORDER BY sessions DESC"
        )
        rows = con.execute(
            f"SELECT segment, sessions, median_duration_s, p90_duration_s, median_duration_s_multi_event, p90_duration_s_multi_event, single_event_share FROM read_parquet({dur}) WHERE segment_type = '{seg}' {order}{extra}"
        ).fetchall()
        md += ["", f"### Session duration by {title}", ""]
        md.append(
            _table(
                [
                    "Segment",
                    "Sessions",
                    "Median (s)",
                    "p90 (s)",
                    "Median, 2+ events (s)",
                    "p90, 2+ events (s)",
                    "Single-event",
                ],
                [
                    [
                        s_,
                        _fmt(n),
                        _fmt(a, digits=0),
                        _fmt(b, digits=0),
                        _fmt(c, digits=0),
                        _fmt(d, digits=0),
                        _fmt(e, pct=True),
                    ]
                    for s_, n, a, b, c, d, e in rows
                ],
            )
        )
    md.append("")
    return md


def _user_session_section(paths: Paths, con, months: list[str], figs: Path, log) -> list[str]:
    md = [
        "## How these sessions differ from the dataset's `user_session`",
        "",
        "`user_session` is the store's own session id. It is not an inactivity rule: it changes between "
        "events seconds apart and stays the same across gaps of hours or days (see `reports/profile_*.txt`). "
        "Exact match = my session and a `user_session` id contain exactly the same events.",
        "",
    ]
    sens_rows = []
    diff_rows = []
    for m in months:
        stem = MONTH_FILES[m].removesuffix(".csv")
        days = [d for d in list_partitions(paths.sessionized) if d.isoformat()[:7] == m]
        files = ", ".join(
            sql_str(str(paths.sessionized / f"event_date={d.isoformat()}" / "part-0.parquet")) for d in days
        )
        t = time.perf_counter()
        con.execute("DROP TABLE IF EXISTS g")
        con.execute(
            f"""CREATE TEMP TABLE g AS
                SELECT user_id, user_session, session_id,
                       (epoch_us(event_time) - epoch_us(lag(event_time) OVER w)) / 1e6 AS gap_s,
                       row_number() OVER w AS rn
                FROM read_parquet([{files}], hive_partitioning=false)
                WINDOW w AS (PARTITION BY user_id ORDER BY event_time, source_file, source_row)"""
        )
        # One window pass computes the session number for every N, then one GROUP BY per N.
        keys = ", ".join(
            f"sum((gap_s IS NULL OR gap_s > {n * 60})::INT) OVER w AS k{n}" for n in SENSITIVITY_MINUTES
        )
        con.execute("DROP TABLE IF EXISTS k")
        con.execute(
            f"CREATE TEMP TABLE k AS SELECT user_id, user_session, {keys} FROM g "
            "WINDOW w AS (PARTITION BY user_id ORDER BY rn ROWS UNBOUNDED PRECEDING)"
        )
        con.execute("DROP TABLE IF EXISTS theirs")
        con.execute(
            "CREATE TEMP TABLE theirs AS SELECT user_session, count(*) AS n FROM g WHERE user_session IS NOT NULL GROUP BY 1"
        )
        for n_min in SENSITIVITY_MINUTES:
            r = con.execute(
                f"""WITH mine AS (
                      SELECT count(DISTINCT user_session) AS nus, min(user_session) AS us, count(*) AS n
                      FROM k GROUP BY user_id, k{n_min})
                    SELECT count(*), count(*) FILTER (m.nus = 1 AND m.n = t.n)
                    FROM mine m LEFT JOIN theirs t ON t.user_session = m.us"""
            ).fetchone()
            sens_rows.append([m, n_min, _fmt(r[0]), _fmt(r[1]), _fmt(r[1] / r[0], pct=True, digits=3)])
        # differences at the configured gap, using the pipeline's own session ids
        d = con.execute(
            """WITH mine AS (SELECT session_id, count(DISTINCT user_session) AS nus, min(user_session) AS us, count(*) AS n FROM g GROUP BY 1),
                     ids AS (SELECT user_session, count(DISTINCT session_id) AS nmine, count(DISTINCT user_id) AS nusers, count(*) AS n FROM g WHERE user_session IS NOT NULL GROUP BY 1)
                SELECT (SELECT count(*) FROM mine), (SELECT count(*) FROM ids),
                       (SELECT count(*) FROM mine m JOIN ids t ON t.user_session = m.us WHERE m.nus = 1 AND m.n = t.n),
                       (SELECT count(*) FROM mine WHERE nus > 1),
                       (SELECT count(*) FROM ids WHERE nmine > 1),
                       (SELECT count(*) FROM ids WHERE nusers > 1)"""
        ).fetchone()
        diff_rows.append(
            [
                m,
                _fmt(d[0]),
                _fmt(d[1]),
                _fmt(d[2]),
                _fmt(d[2] / d[0], pct=True, digits=2),
                _fmt(d[3]),
                _fmt(d[4]),
                _fmt(d[5]),
            ]
        )
        log(f"report: user_session comparison for {m} ({stem}) in {time.perf_counter() - t:.0f}s")
    for tbl in ("g", "k", "theirs"):
        con.execute(f"DROP TABLE IF EXISTS {tbl}")
    md.append(
        _table(
            [
                "Month",
                "My sessions",
                "user_session ids",
                "Exact matches",
                "Share of my sessions",
                "My sessions spanning 2+ ids (merges)",
                "ids split across 2+ of my sessions (splits)",
                "ids shared by 2+ users",
            ],
            diff_rows,
        )
    )
    md += [
        "",
        "Counted over each month's event partitions, so a session that continues from the last day of the "
        "previous month is counted in both months (hence slightly more sessions than in the overview).",
        "",
        "Why they differ: (1) the store starts a new id after very short gaps (merges on my side); "
        "(2) it keeps an id across long inactivity, up to days (splits on my side); (3) a few ids are shared "
        "by more than one user, which can never match a per-user session.",
        "",
        "### Sensitivity to the inactivity threshold N",
        "",
        f"Sessions and exact-match share for other values of N (silver events). The pipeline uses N = {config.SESSION_GAP_MINUTES}.",
        "",
        _table(["Month", "N (min)", "Sessions", "Exact matches", "Exact match share"], sens_rows),
        "",
        "![Sensitivity](figures/sensitivity.png)",
        "",
    ]
    _sensitivity_plot(figs / "sensitivity.png", sens_rows, months)
    return md


def _duration_labels() -> list[str]:
    def h(s: int) -> str:
        if s >= 3600:
            return f"{s // 3600}h"
        if s >= 60:
            return f"{s // 60}m"
        return f"{s}s"

    b = DURATION_BINS
    labels = ["0s"]
    for lo, hi in zip(b[1:-2], b[2:-1], strict=True):
        labels.append(f"{h(lo)}-{h(hi)}")
    labels.append(f">= {h(b[-2])}")
    return labels


def _plt():
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    return plt


def _bar(out: Path, labels: list[str], values: list[float], ylabel: str, title: str) -> None:
    plt = _plt()
    fig, ax = plt.subplots(figsize=(9, 3.6), dpi=150)
