def _grouped_bar(
    out: Path, stages: list[str], series: dict[str, list[float]], ylabel: str, title: str, log_y=False
) -> None:
    plt = _plt()
    fig, ax = plt.subplots(figsize=(7, 3.6), dpi=150)
    n = len(series)
    w = 0.8 / n
    for i, (name, vals) in enumerate(series.items()):
        xs = [x + (i - (n - 1) / 2) * w for x in range(len(stages))]
        ax.bar(xs, vals, width=w * 0.92, color=PALETTE[i], label=name)
    ax.set_xticks(range(len(stages)), stages)
    if log_y:
        ax.set_yscale("log")
    ax.set_ylabel(ylabel + (" (log scale)" if log_y else ""))
    ax.set_title(title, loc="left")
    style_axes(ax)
    ax.legend(frameon=False, fontsize=8)
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)


def _sensitivity_plot(out: Path, rows: list[list], months: list[str]) -> None:
    plt = _plt()
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(9, 3.4), dpi=150)
    for i, m in enumerate(months):
        sel = [r for r in rows if r[0] == m]
        xs = [r[1] for r in sel]
        a1.plot(
            xs,
            [int(r[2].replace(",", "")) / 1e6 for r in sel],
            color=PALETTE[i],
            lw=2,
            marker="o",
            ms=4,
            label=m,
        )
        a2.plot(xs, [float(r[4].rstrip("%")) for r in sel], color=PALETTE[i], lw=2, marker="o", ms=4, label=m)
    for ax, title, yl in [
        (a1, "Sessions", "Sessions (millions)"),
        (a2, "Exact match with user_session", "Share of my sessions (%)"),
    ]:
        ax.set_xscale("log")
        ax.set_xticks(list(SENSITIVITY_MINUTES), [str(x) for x in SENSITIVITY_MINUTES])
        ax.minorticks_off()
        ax.axvline(config.SESSION_GAP_MINUTES, color="#b5b3ad", lw=1, ls="--")
        ax.set_xlabel("Inactivity threshold N (minutes)")
        ax.set_ylabel(yl)
        ax.set_title(title, loc="left")
        style_axes(ax)
    a1.legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)


